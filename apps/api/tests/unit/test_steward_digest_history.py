_ENTRY_IDS = [entry["file"] for entry in MANIFEST["entries"]]


def _entry(file_name: str) -> dict[str, object]:
    return next(item for item in MANIFEST["entries"] if item["file"] == file_name)


@pytest.mark.parametrize("file_name", _ENTRY_IDS)
def test_frozen_fixture_bytes_match_their_artifact_digest(file_name: str) -> None:
    """The fixtures carry self-verifying provenance: content address over their own bytes."""

    entry = _entry(file_name)
    raw = (FIXTURE_DIR / file_name).read_bytes()

    assert len(raw) == entry["byte_size"]
    assert hashlib.sha256(raw).hexdigest() == entry["artifact_sha256"]


@pytest.mark.parametrize("file_name", _ENTRY_IDS)
def test_stored_envelopes_still_round_trip_to_identical_canonical_bytes(file_name: str) -> None:
    entry = _entry(file_name)
    raw = (FIXTURE_DIR / file_name).read_bytes()
    envelope = _ENVELOPES[str(entry["model"])].model_validate(json.loads(raw))

    assert canonical_sha256(envelope.content) == entry["content_sha256"]
    assert canonical_json_bytes(envelope) == raw


def test_stored_authority_binding_digest_is_unchanged() -> None:
    raw = (FIXTURE_DIR / "authority-binding.json").read_bytes()
    binding = SignedAuthorityBinding.model_validate(json.loads(raw))

    assert binding.content.materialization_run_id == MATERIALIZATION_RUN_ID
    assert binding.binding_sha256 == AUTHORITY_BINDING_SHA256
    assert canonical_sha256(binding.content) == AUTHORITY_BINDING_SHA256
    assert binding.attestation.statement_sha256 == AUTHORITY_BINDING_SHA256
    assert canonical_json_bytes(binding) == raw


@pytest.mark.skipif(
    not (ARTIFACT_STORE / "sha256").is_dir(),
    reason=(
        "local steward artifact store is absent; the 53 MB materialization report cannot be "
        "vendored into the repository. Set MED_RAG_STEWARD_ARTIFACT_STORE to verify it."
    ),
)
def test_stored_materialization_report_digest_is_unchanged() -> None:
    matches = list(ARTIFACT_STORE.rglob(f"{MATERIALIZATION_REPORT_ARTIFACT_SHA256}.blob"))
    if not matches:
        pytest.skip("materialization report artifact is not preserved in this artifact store")
    raw = matches[0].read_bytes()

    assert hashlib.sha256(raw).hexdigest() == MATERIALIZATION_REPORT_ARTIFACT_SHA256

    report = MaterializationReport.model_validate(json.loads(raw))

    assert report.content.materialization_run_id == MATERIALIZATION_RUN_ID
    assert report.report_sha256 == MATERIALIZATION_REPORT_SHA256
    assert canonical_sha256(report.content) == MATERIALIZATION_REPORT_SHA256
    assert canonical_json_bytes(report) == raw
    # The stored report predates compact evidence entries. It survives only because the
    # field was widened by union rather than replaced -- the precedent the narrative-only
    # binding follows.
    assert all(isinstance(item, MaterializedEvidenceRecord) for item in report.content.evidence)
    assert report.content.authority_binding.binding_sha256 == AUTHORITY_BINDING_SHA256


