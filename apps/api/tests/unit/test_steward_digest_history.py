"""Guardrail: signed steward content must keep its canonical bytes forever.

``canonical_json_bytes`` is a bare ``model_dump(mode="json")``, and the signed envelopes
recompute their digest on every ``model_validate``. Adding a field to any content model in
this graph -- including an optional one defaulting to ``None``, which still serializes --
silently rewrites the canonical bytes of already-signed records, and every stored
authority binding, materialization report and corpus release candidate stops loading.

The fixtures here are byte-frozen copies of real artifacts from the WHO SMART HIV
materialization run, lifted verbatim out of the content-addressed artifact store. They are
never regenerated by application code, so they cannot drift with the schemas they pin.

See docs/narrative-only-materialization.md for why this gates the narrative-only work.
"""

